/**
 * 根据名称获取 icon
 * @param iconName 名称
 * @constructor
 */
const LoadIcon = (iconName: string) => {
  return IconMap[iconName];
};

/**
 * 根据文件类型获取 icon
 * @param filetype 文件类型
 * @constructor
 */
const LoadFileIcon = (filetype: string) => {
  const type = filetype.toLowerCase();
  const iconFunc = LoadIcon(type);
  if (iconFunc) {
    return iconFunc;
  }
  return UnknownFileIcon;
};

